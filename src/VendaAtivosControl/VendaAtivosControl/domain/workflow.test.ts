import { describe, expect, it } from "vitest";
import {
    emptyRequest,
    parseChoices,
    parsePermissions,
    serializableRequest
} from "./sharePointSchema";
import { validateRequest } from "./workflow";
import { SaleRequest } from "./types";

function validRequest(): SaleRequest {
    return {
        ...emptyRequest,
        Title: "Empilhadeira 01",
        Tipo: "Equipamento",
        Area: "Operações",
        Empresa: "Empresa Teste",
        UnidadePlanta: "Planta 1",
        ModalidadeVenda: "Leilão",
        Prioridade: "Normal",
        ValorEstimadoTotal: 50000,
        ParecerTecnico: "Ativo liberado para venda."
    };
}

describe("SharePoint schema bridge", () => {
    it("parses Power Fx choice records", () => {
        const choices = parseChoices(JSON.stringify({
            Tipo: [{ Value: "Veículo" }],
            Empresa: [{ Value: "Empresa A" }]
        }));

        expect(choices.Tipo).toEqual(["Veículo"]);
        expect(choices.Empresa).toEqual(["Empresa A"]);
        expect(choices.Prioridade).toContain("Urgente");
    });

    it("parses action tables generated by Power Fx", () => {
        const permissions = parsePermissions(JSON.stringify({
            actions: [{ Value: "approveManager" }, { Value: "unknown" }],
            canEdit: false
        }));

        expect(permissions.actions).toEqual(["approveManager"]);
        expect(permissions.canEdit).toBe(false);
    });

    it("removes SharePoint-managed fields from submissions", () => {
        const request = {
            ...validRequest(),
            ID: 42,
            Created: "2026-07-30T20:00:00Z",
            Attachments: true
        };
        const output = serializableRequest(request);

        expect(output).not.toHaveProperty("ID");
        expect(output).not.toHaveProperty("Created");
        expect(output).not.toHaveProperty("Attachments");
    });
});

describe("workflow validation", () => {
    it("accepts a complete initial request", () => {
        expect(validateRequest(validRequest()).valid).toBe(true);
    });

    it("requires fiscal identifiers at fiscal completion", () => {
        const result = validateRequest(validRequest(), "completeFiscal");
        expect(result.valid).toBe(false);
        expect(result.errors.NumeroOVSAP).toBeTruthy();
        expect(result.errors.NumeroNF).toBeTruthy();
    });

    it("requires final sale data and a valid URL", () => {
        const request = {
            ...validRequest(),
            ValorFinalVenda: 47000,
            ClienteComprador: "Comprador Ltda.",
            FormularioBaixaCoA: "not-a-url"
        };
        const invalid = validateRequest(request, "conclude");
        expect(invalid.errors.FormularioBaixaCoA).toBeTruthy();

        request.FormularioBaixaCoA = "https://empresa.sharepoint.com/baixa/42";
        expect(validateRequest(request, "conclude").valid).toBe(true);
    });
});
